// pcam_infer.hpp — types and dimensions for the PCam INT8 inference kernel.
//
// Phase 2 bring-up version. No pragmas anywhere in this design yet: the
// only goal is bit-exact agreement with phase1_software/golden.py in C
// simulation. Optimization comes after that, one pragma per synthesis
// run, logged in phase2_hls/reports/DSE_LOG.md.
//
// Everything structural here is dictated by golden.py. If a value in this
// file disagrees with that one, golden.py is right.

#ifndef PCAM_INFER_HPP
#define PCAM_INFER_HPP

#include <ap_int.h>
#include "params.h"          // generated by export.py — dimensions only

// ---------------------------------------------------------------------
// Datapath types
// ---------------------------------------------------------------------
// Activations are uint8 with zero-point 0. Legal because every stored
// activation is post-ReLU and therefore non-negative, which is what lets
// this kernel skip zero-point correction entirely and treat a zero pad as
// a literal integer zero.
typedef ap_uint<8>  px_t;     // activations, and raw input tile bytes
typedef ap_int<8>   wt_t;     // weights, symmetric per output channel
typedef ap_int<32>  acc_t;    // convolution accumulator, bias, M0, shift
typedef ap_int<32>  score_t;  // output logits

// Requantization intermediate. acc peaks near 2^25 in practice and M0 is
// held in [2^30, 2^31) by export.py, so the product needs about 56 bits.
// This MUST be 64 bits wide; a 32-bit intermediate silently wraps and the
// mismatch against golden.py shows up as scattered wrong tiles rather
// than an obvious failure.
typedef ap_int<64>  mul_t;

// Native int for loop counters only. Never for datapath values.

// ---------------------------------------------------------------------
// Spatial dimensions per stage, derived from the 96x96 input
// ---------------------------------------------------------------------
#define H1 96
#define H2 48
#define H3 24
#define H4 12
#define H5 6

// ---------------------------------------------------------------------
// Flat offsets into the weight and parameter blobs
// ---------------------------------------------------------------------
// The testbench splits export.py's weights.bin into two contiguous
// blobs — all int8 weights in layer order, all int32 parameters in layer
// order — because mixing widths in one AXI port is not worth the trouble
// during bring-up. These offsets are the contract between the two.
//
// Layer order throughout: conv1..conv5, gap, fc. Same as
// golden.CONV_STAGES + ["gap", "fc"].

#define W_CONV1 (CONV1_OUT * CONV1_IN * 9)
#define W_CONV2 (CONV2_OUT * CONV2_IN * 9)
#define W_CONV3 (CONV3_OUT * CONV3_IN * 9)
#define W_CONV4 (CONV4_OUT * CONV4_IN * 9)
#define W_CONV5 (CONV5_OUT * CONV5_IN * 9)
#define W_FC    (FC_OUT * FC_IN)

#define WOFF_CONV1 0
#define WOFF_CONV2 (WOFF_CONV1 + W_CONV1)
#define WOFF_CONV3 (WOFF_CONV2 + W_CONV2)
#define WOFF_CONV4 (WOFF_CONV3 + W_CONV3)
#define WOFF_CONV5 (WOFF_CONV4 + W_CONV4)
#define WOFF_FC    (WOFF_CONV5 + W_CONV5)
#define W_TOTAL    (WOFF_FC + W_FC)          // 134,320 int8

// Each conv contributes bias, m0, shift (3 arrays of OUT). GAP the same.
// FC contributes bias only, since its output is not requantized.
#define POFF_CONV1 0
#define POFF_CONV2 (POFF_CONV1 + 3 * CONV1_OUT)
#define POFF_CONV3 (POFF_CONV2 + 3 * CONV2_OUT)
#define POFF_CONV4 (POFF_CONV3 + 3 * CONV3_OUT)
#define POFF_CONV5 (POFF_CONV4 + 3 * CONV4_OUT)
#define POFF_GAP   (POFF_CONV5 + 3 * CONV5_OUT)
#define POFF_FC    (POFF_GAP   + 3 * GAP_CH)
#define P_TOTAL    (POFF_FC + FC_OUT)

// Within a layer's parameter block: bias, then m0, then shift.
#define PB(off, n) ((off))                 // bias   base
#define PM(off, n) ((off) + (n))           // m0     base
#define PS(off, n) ((off) + 2 * (n))       // shift  base

// ---------------------------------------------------------------------
// Top level
// ---------------------------------------------------------------------
// tiles   n_tiles * TILE_BYTES, CHW, contiguous — the same bytes
//         data.py --dump-bin writes and golden.py reads.
// scores  n_tiles * FC_OUT int32 logits. The host computes
//         scores[2*i+1] - scores[2*i] and thresholds at zero.
extern "C" void pcam_infer(const wt_t   *w_blob,
                           const acc_t  *p_blob,
                           const px_t   *tiles,
                           score_t      *scores,
                           int           n_tiles);

#endif  // PCAM_INFER_HPP